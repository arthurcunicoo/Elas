import assert from 'node:assert/strict';
import { categoryForPlace, matchesCategory, placeTypeLabel, groupMapPoints, distanceBetween } from '../constants/placeCategories.ts';
const place=(id,category,latitude=-28.678,longitude=-49.369)=>({id,category,name:id,address:'Criciúma',latitude,longitude,status:'unknown'});
assert.equal(categoryForPlace(place('park','park')).id,'parks');
assert.equal(categoryForPlace(place('food','restaurant')).id,'restaurants');
assert.equal(categoryForPlace(place('fast','fast_food')).id,'restaurants');
assert.equal(categoryForPlace(place('coffee','cafe')).id,'cafes');
assert.equal(categoryForPlace(place('store','supermarket')).id,'markets');
assert.equal(categoryForPlace(place('med','pharmacy')).id,'health');
assert.equal(categoryForPlace(place('class','school')).id,'education');
assert.equal(categoryForPlace(place('gym','fitness_centre')).id,'sports');
assert.equal(categoryForPlace(place('bank','bank')).id,'services');
assert.equal(categoryForPlace(place('shirt','clothes')).id,'shops');
assert.equal(categoryForPlace(place('new','unrecognised_type')).id,'other');
assert.equal(categoryForPlace(place('congresso',null)).id,'other');
assert.equal(categoryForPlace(place('unknown',null)).id,'other');
assert.equal(placeTypeLabel(place('med','pharmacy')),'Farmácia');
assert.ok(matchesCategory(place('park','park'),'all'));
assert.ok(!matchesCategory(place('park','park'),'restaurants'));
const region={latitude:-28.678,longitude:-49.369,latitudeDelta:.016,longitudeDelta:.016};
const rows=[place('one','park'),place('two','restaurant'),place('far','school',-28.683,-49.372)];
const points=groupMapPoints(rows,region,{width:390,height:700});
assert.equal(points.length,2);
assert.equal(points.flatMap(point=>point.places).length,rows.length);
assert.equal(new Set(points.flatMap(point=>point.places.map(place=>place.id))).size,rows.length);
const selected=groupMapPoints(rows,region,{width:390,height:700},'one');
assert.ok(selected.some(point=>point.places.length===1&&point.places[0].id==='one'));
assert.equal(selected.flatMap(point=>point.places).length,rows.length);
assert.deepEqual(groupMapPoints(rows,region,{width:0,height:700}),[]);
assert.equal(distanceBetween(rows[0],rows[0]),0);
assert.ok(distanceBetween(rows[0],rows[2])>.1);
assert.equal(categoryForPlace({...place('manual','park'),appCategory:'restaurants'}).id,'restaurants');
assert.equal(placeTypeLabel({...place('manual','park'),appCategory:'restaurants'}),'Restaurante');
console.log('27 map checks passed: OSM category mapping, fallback, filtering, clustering, selected place visibility and distance sorting.');
