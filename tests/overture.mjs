import assert from 'node:assert/strict';
import { prepareCatalog, overtureCategory } from '../scripts/overture_catalog.mjs';
const known=[{id:'existing',nome:'Praça teste',endereco:'Criciúma · SC',latitude:-28.678,longitude:-49.369,categoria:'park'}];
const feature=(id,name='Praça teste',longitude=-49.369)=>({type:'Feature',geometry:{type:'Point',coordinates:[longitude,-28.678]},properties:{id,names:{primary:name},confidence:.95,basic_category:'public_plaza',taxonomy:{primary:'public_plaza',hierarchy:['community_and_government','public_plaza']},addresses:[{country:'BR',locality:'Criciúma',freeform:'Rua A, 12'}],sources:[]}});
const first=feature('11111111-1111-4111-8111-111111111111');
const snapshot=features=>({type:'FeatureCollection',release:'2026-09-23.1',bbox:[-49.39,-28.72,-49.34,-28.66],features});
assert.equal(prepareCatalog(snapshot([first]),known).records[0].target_id,'existing');
assert.equal(prepareCatalog(snapshot([first,first]),known).stats.accepted,1);
const distant=feature('22222222-2222-4222-8222-222222222222','Praça teste',-49.372);
assert.equal(prepareCatalog(snapshot([distant]),known).records[0].target_id,null,'same-name distinct branch is not merged');
assert.equal(prepareCatalog(snapshot([first]),[...known,{...known[0],id:'second'}]).review.length,1);
const low=structuredClone(first);low.properties.confidence=.5;
assert.equal(prepareCatalog(snapshot([low]),known).records.length,0);
const house=feature('33333333-3333-4333-8333-333333333333','Condomínio Privado');
assert.equal(prepareCatalog(snapshot([house]),known).stats.rejected.not_public_destination,1);
const closed=structuredClone(first);closed.properties.operating_status='permanently_closed';
assert.equal(prepareCatalog(snapshot([closed]),known).stats.rejected.closed,1);
const foreign=structuredClone(first);foreign.properties.addresses[0].locality='Içara';
assert.equal(prepareCatalog(snapshot([foreign]),known).stats.rejected.city_not_confirmed,1);
const conflicting=[{...known[0],endereco:'Rua A, 5 · Criciúma · SC'}];
assert.equal(prepareCatalog(snapshot([first]),conflicting).review.length,1);
assert.equal(overtureCategory('public_plaza',['community_and_government']),'parks');
assert.equal(overtureCategory('pizza_restaurant',['food_and_drink']),'restaurants');
assert.equal(overtureCategory('grocery_store',['shopping']),'markets');
assert.equal(overtureCategory('dental_clinic',['health_care']),'health');
assert.equal(overtureCategory('pharmacy',['shopping','health_and_personal_care_store']),'health','a retail taxonomy parent must not hide a pharmacy from Saúde');
assert.throws(()=>prepareCatalog({...snapshot([]),release:null},known));
console.log('Overture checks passed: GERS uniqueness, category taxonomy, conservative matching, branches, ambiguous overlaps, low confidence, closures and residential filtering.');
